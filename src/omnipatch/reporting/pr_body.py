"""Render a verified patch as a safe, metadata-only pull request body."""

from omnipatch.codebase.redaction import redact
from omnipatch.models import Finding, PatchResult


def pull_request_title(finding: Finding) -> str:
    """Build the bounded pull request title from finding metadata."""
    title = redact(finding.title)
    file_name = redact(finding.file.as_posix())
    return f"fix({finding.rule_id}): {title} in {file_name}"[:72]


def render_pull_request_body(
    result: PatchResult,
    finding: Finding,
    required_environment: tuple[str, ...] = (),
    sql_paramstyle: str | None = None,
) -> str:
    """Render Markdown describing one verified security patch."""
    if not result.verified:
        raise ValueError("Cannot render a pull request body for an unverified patch")
    cwe = redact(finding.cwe or "Not available")
    file_name = redact(finding.file.as_posix())
    if result.introduced:
        verification = [
            "The target finding is gone. The severity policy accepted these lower-severity findings introduced by the fix:",
            *(f"- {redact(label)}" for label in result.introduced),
            "A human reviewer must assess this severity trade-off before merge.",
        ]
    else:
        verification = [
            "The patched file was re-scanned in isolation. The target finding is gone, and no new finding appeared."
        ]
    body = [
        f"Verified security fix for {finding.rule_id} in `{file_name}`.",
        "",
        "| Rule | Severity | CWE | File | Line |",
        "|---|---|---|---|---:|",
        f"| {finding.rule_id} | {finding.severity.value} | {cwe} | `{file_name}` | {finding.line_start} |",
        "",
        "### Change",
        redact(result.patch.explanation),
        "",
        "### Verification",
        *verification,
        "",
        "This change was generated by a language model. A human must review it before merge.",
    ]
    if required_environment:
        insertion = body.index("### Verification")
        body[insertion:insertion] = [
            "### Required environment",
            "The patched module reads these environment variables at import and will fail to start if any is unset:",
            *(f"- `{redact(name)}`" for name in dict.fromkeys(required_environment)),
            "",
        ]
    if sql_paramstyle is not None:
        insertion = body.index("### Verification")
        body[insertion:insertion] = [
            "### Assumptions",
            f"SQL parameter style: `{redact(sql_paramstyle)}`. This value came from explicit configuration; it was not detected from the source.",
            "",
        ]
    return "\n".join(body)
